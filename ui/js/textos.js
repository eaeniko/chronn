/** Os dicionários, pelo código do idioma. */
export const DICIONARIOS = { 'pt-BR': PT, en: EN };

/** Os idiomas da interface, na ordem dos Ajustes, com o nome de cada um no próprio idioma. */
export const IDIOMAS = [
  { id: 'pt-BR', nome: 'Português (Brasil)', lang: 'pt-BR', locale: 'pt-BR' },
  { id: 'en', nome: 'English', lang: 'en', locale: 'en-US' },
];

/** O valor da config que segue o Windows (o padrão). */
export const IDIOMA_SISTEMA = 'sistema';

/**
 * O idioma que vale: `escolha` ("pt-BR", "en" ou "sistema") e, no "sistema", o idioma do Windows
 * (`sistema`, como o `navigator.language`): começa com "pt" → português; qualquer outro → inglês.
 */
export function resolverIdioma(escolha, sistema) {
  if (escolha === 'pt-BR' || escolha === 'en') return escolha;
  return /^pt\b/i.test(String(sistema ?? '').trim()) ? 'pt-BR' : 'en';
}

let atual = 'pt-BR';
const ouvintes = new Set();

/** O idioma de agora ("pt-BR" ou "en"). */
export const idiomaAtual = () => atual;

/** O locale do `Intl` do idioma de agora. */
export const localeAtual = () => IDIOMAS.find((i) => i.id === atual)?.locale ?? 'pt-BR';

/**
 * Troca o idioma da interface. Devolve se mudou; mudando, avisa quem pediu (`aoTrocarIdioma`) e
 * a página redesenha.
 */
export function definirIdioma(id) {
  const novo = DICIONARIOS[id] ? id : 'pt-BR';
  if (novo === atual) return false;
  atual = novo;
  for (const f of ouvintes) f(atual);
  return true;
}

/** `fn(idioma)` a cada troca de idioma. */
export function aoTrocarIdioma(fn) {
  ouvintes.add(fn);
  return () => ouvintes.delete(fn);
}

/**
 * Os textos no idioma de agora: `TEXTOS.chave` ou `TEXTOS.chave(parâmetros)`. Uma chave que não
 * existe no idioma cai no português (o teste garante que não acontece).
 */
export const TEXTOS = new Proxy(
  {},
  {
    get: (_, k) => (k in DICIONARIOS[atual] ? DICIONARIOS[atual][k] : PT[k]),
    has: (_, k) => k in PT,
    ownKeys: () => Reflect.ownKeys(PT),
    getOwnPropertyDescriptor: (_, k) => (k in PT ? { enumerable: true, configurable: true, value: TEXTOS[k] } : undefined),
  },
);

/**
 * Põe os textos fixos do HTML no idioma de agora: `data-texto` (o texto), `data-dica` (o `title`),
 * `data-rotulo` (o `aria-label`) e `data-texto-app` (um texto com o nome do app); e o `lang` do
 * `<html>`. Na carga e a cada troca de idioma.
 */
export function aplicarTextos(doc, nomeApp = globalThis.NOME_APP ?? '') {
  doc.documentElement.lang = IDIOMAS.find((i) => i.id === atual)?.lang ?? 'pt-BR';
  const por = (sel, f) => {
    for (const el of doc.querySelectorAll(sel)) f(el);
  };
  por('[data-texto]', (el) => {
    const t = TEXTOS[el.dataset.texto];
    if (typeof t === 'string' && el.textContent !== t) el.textContent = t;
  });
  por('[data-texto-app]', (el) => {
    const t = TEXTOS[el.dataset.textoApp]?.(nomeApp);
    if (typeof t === 'string' && el.textContent !== t) el.textContent = t;
  });
  por('[data-dica]', (el) => {
    const t = TEXTOS[el.dataset.dica];
    if (typeof t === 'string' && el.getAttribute('title') !== t) el.setAttribute('title', t);
  });
  por('[data-rotulo]', (el) => {
    const t = TEXTOS[el.dataset.rotulo];
    if (typeof t === 'string') el.setAttribute('aria-label', t);
  });
}

/**
 * O idioma da primeira pintura, antes do primeiro estado: o último usado (guardado pela página) ou
 * o do Windows.
 */
export const CHAVE_IDIOMA = 'worktimer.idioma';
export function idiomaInicial(guardado, sistema) {
  return DICIONARIOS[guardado] ? guardado : resolverIdioma(IDIOMA_SISTEMA, sistema);
}

/**
 * O idioma de um estado do núcleo: o que ele diz que vale (`idioma`, com o "sistema" resolvido
 * pelo Windows, o mesmo das perguntas); sem ele, a escolha da config com o `sistema` daqui.
 */
export const idiomaDoEstado = (s, sistema) => (DICIONARIOS[s?.idioma] ? s.idioma : resolverIdioma(s?.config?.idioma, sistema));

